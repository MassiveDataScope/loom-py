from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Generic, TypeVar

from loom.core.errors import JobFailedError, JobTimeoutError

ResultT = TypeVar("ResultT")


@dataclass
class InlineOutcome:
    """How an inline job ended: still pending, a result, or the error it raised.

    The first outcome recorded settles it; a later failure, such as a
    success callback raising, leaves a recorded result in place.
    """

    _result: Any = None
    _error: Exception | None = None
    _settled: bool = False

    def succeed(self, result: Any) -> None:
        """Record the job's *result*."""
        self._result, self._settled = result, True

    def fail(self, error: Exception) -> None:
        """Record *error* as the job's failure unless the outcome is already settled."""
        if not self._settled:
            self._error, self._settled = error, True

    def unwrap(self, job_id: str, timeout: float | None) -> Any:
        """Return the recorded result.

        Args:
            job_id: The job this outcome belongs to.
            timeout: The wait's timeout, reported when the job has not run.

        Returns:
            The value returned by ``Job.execute()``.

        Raises:
            JobFailedError: If the job raised.
            JobTimeoutError: If the job has not run yet.
        """
        error = self._error
        if error is not None:
            raise JobFailedError(job_id, error)
        if not self._settled:
            raise JobTimeoutError(job_id, timeout)
        return self._result


@dataclass(frozen=True)
class JobHandle(Generic[ResultT]):
    """Represents a dispatched job and allows waiting for its result.

    Created by ``JobService.dispatch_after_commit()`` immediately — before the job is
    actually sent to the broker.  The ``job_id`` is a UUID generated by the
    framework and passed to Celery as ``task_id`` so both sides share the
    same identifier.

    Only an inline job settles its handle: the inline runner records the
    result or error in ``_inline_outcome`` after execution, and ``wait()``
    unwraps it. A handle of a job sent to a broker is never settled here.

    Attributes:
        job_id: UUID pre-generated by the framework and shared with Celery.
        queue: The Celery queue the job was dispatched to.
        dispatched_at: UTC timestamp of when the handle was created.

    Args:
        job_id: UUID string.
        queue: Target queue name.
        dispatched_at: UTC timestamp.
        _inline_outcome: Outcome settled by the inline runner.

    Example::

        handle = service.dispatch_after_commit(SendEmailJob, payload={"user_id": 1})
        result = handle.wait(timeout=10.0)
    """

    job_id: str
    queue: str
    dispatched_at: datetime
    _inline_outcome: InlineOutcome = field(default_factory=InlineOutcome, repr=False, compare=False)

    def wait(self, timeout: float | None = None) -> ResultT:
        """Return the result the inline runner recorded.

        Args:
            timeout: The wait's timeout, reported when the job has not run.

        Returns:
            The value returned by ``Job.execute()``.

        Raises:
            JobTimeoutError: If the job has not run yet.
            JobFailedError: If the job raised an exception.
        """
        return self._inline_outcome.unwrap(self.job_id, timeout)  # type: ignore[no-any-return]


@dataclass(frozen=True)
class JobGroup:
    """Represents a group of concurrently dispatched jobs.

    Created by ``JobService.dispatch_parallel()``.  ``wait_all()`` collects
    every result.

    Attributes:
        handles: Ordered tuple of handles, one per dispatched job.

    Example::

        group = service.dispatch_parallel([
            (SendEmailJob, {"user_id": 1}),
            (SendEmailJob, {"user_id": 2}),
        ])
        results = group.wait_all(timeout=30.0)
    """

    handles: tuple[JobHandle[Any], ...]

    def wait_all(self, timeout: float | None = None) -> list[Any]:
        """Wait for every handle and return results in dispatch order.

        Args:
            timeout: Per-handle timeout in seconds.  ``None`` waits
                indefinitely for each handle.

        Returns:
            List of results aligned with ``handles`` order.

        Raises:
            JobTimeoutError: If any handle exceeds ``timeout``.
            JobFailedError: If any job failed.
        """
        return [handle.wait(timeout) for handle in self.handles]
